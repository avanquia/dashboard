import type { Card, Client, Priority } from "@/lib/types";

type Status = "Feito" | "Em revisão" | "Não feito";

const STATUS_COLUMN = { Feito: "done", "Em revisão": "review", "Não feito": "backlog" } as const;

function card(
  section: string,
  id: string,
  title: string,
  status: Status,
  repo: string | null,
  priority: Priority | null,
  details: string,
  doneWhen?: string,
): Card {
  return {
    id,
    section,
    title,
    column: STATUS_COLUMN[status],
    repo: repo ?? undefined,
    priority: priority ?? undefined,
    details,
    doneWhen,
  };
}

type CardArgs = Parameters<typeof card> extends [string, ...infer R] ? R : never;
const inSection = (section: string) => (...args: CardArgs) => card(section, ...args);

